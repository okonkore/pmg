const assert=require('node:assert/strict');
const {parse,documentFrom}=require('./midi-import.js');
const vlq=n=>{const a=[n&127];while(n>>=7)a.unshift((n&127)|128);return a};
const event=(delta,...bytes)=>[...vlq(delta),...bytes];
const chunk=(tag,data)=>Buffer.concat([Buffer.from(tag),Buffer.from([data.length>>>24,data.length>>>16,data.length>>>8,data.length]),Buffer.from(data)]);
const midi=(tracks,format=tracks.length>1?1:0,division=128)=>Buffer.concat([chunk('MThd',[0,format,0,tracks.length,division>>8,division&255]),...tracks.map(t=>chunk('MTrk',t))]);
const end=[0,255,47,0];
const melody=[...event(0,144,60,100),...event(64,60,80),...event(64,128,60,0),...event(64,60,0),...event(64,144,64,64),...event(128,64,0),...end];
