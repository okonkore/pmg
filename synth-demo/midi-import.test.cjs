 assert.throws(()=>parse(midi([[...event(128,255,81,3,9,39,192),...end]])),/途中でテンポ/);
 assert.throws(()=>parse(midi([[0,255,88,4,3,2,24,8,1,255,88,4,4,2,24,8,...end]])),/途中で拍子/);
 assert.deepEqual(parse(midi([[0,255,88,4,6,3,24,8,...end]])).meter,[6,8]);
 assert.throws(()=>parse(midi([[0,144,60,100,0,240,1,247,1,60,0,...end]])),/ランニング/);
 assert.throws(()=>documentFrom(parse(midi([[0,144,60,100,1,128,60,0,...end]],0,32767)),[0],'short'),/長さ/);
 assert.throws(()=>parse(midi([melody],2)),/形式/);
 assert.throws(()=>parse(midi([melody],0,0xe728)),/SMPTE/);
 assert.throws(()=>parse(fixture.subarray(0,fixture.length-1)),/途中/);
 assert.throws(()=>parse(midi([[0,60,100,...end]])),/ランニング/);
 assert.throws(()=>parse(midi([[0,144,60,100,...end]])),/終了していない/);
 assert.throws(()=>parse(midi([[0,128,60,0,...end]])),/開始音/);
 assert.throws(()=>parse(midi([[0,144,60,100,0,255,1,0,1,60,0,...end]])),/ランニング/);
 assert.throws(()=>parse(midi([[128,128,128,128,0,...end]])),/可変長/);
 assert.throws(()=>parse(new Uint8Array(8*1024*1024+1)),/8MB/);
 assert.throws(()=>documentFrom(parse(midi([[0,144,20,100,128,0,128,20,0,...end]])),[0],'Range'),/音域/);
 const many=[];for(let i=0;i<20001;i++)many.push(0,144,60,1,1,128,60,0);
 assert.throws(()=>parse(midi([[...many,...end]],0,32767)),/20000/);
