 const hugeEvents=Buffer.alloc(500001*3);for(let i=0;i<500001;i++){hugeEvents[i*3+1]=192;}assert.throws(()=>parse(midi([Buffer.concat([hugeEvents,Buffer.from(end)])])),/イベント数/);
 assert.throws(()=>parse(midi(Array.from({length:257},()=>end))),/トラック数/);
