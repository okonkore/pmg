'use strict';
// Passive coupled-mode approximation of a yielding bridge and radiating body.
// Every note uses the same body. Mode amplitudes are energy coordinates.
// This is a reduced near-resonance model, not a measured bridge impedance.
const NylonBridgeModel = {
 // frequency, amplitude decay rate (/s), bridge participation, radiative fraction.
 bodyModes:[[105,65,.45,.15],[190,95,.55,.08],[295,145,1,.85],[420,150,.7,.8],
  [590,230,1.1,.8],[730,210,.55,.45],[920,260,.35,.08],[1028,25,.5,.65],
  [1190,100,1,.9],[1430,340,.4,.12],
  [1850,420,.55,.02],[2610,350,2.348,.9],[3300,800,1,.6],[4350,1050,.6,.45]],
 stringFor(midi,settings){return NylonModel.stringFor(midi,settings)},
 render(rate,midi,settings={},diagnostics){
  const steps=this.renderSteps(rate,midi,settings,diagnostics);let result;
  do{result=steps.next()}while(!result.done);
  return result.value;
 },
 async renderAsync(rate,midi,settings={},diagnostics,scheduler={}){
  const now=scheduler.now||(()=>performance.now());
  const pause=scheduler.pause||(()=>new Promise(resolve=>setTimeout(resolve,8)));
  const steps=this.renderSteps(rate,midi,settings,diagnostics);let result,slice=now();
  while(!(result=steps.next()).done){if(now()-slice>=6){await pause();slice=now()}}
  return result.value;
 },
 renderSteps(rate,midi,{nail=.38,position=.22,body=.48,dropD=false,contact=0,attack=0,bodyFit=0,referenceTone=0,stringTexture=0,highDecay=0,thirdTone=0,firstTone=0}={},diagnostics){
  const fit=bodyFit?(referenceTone?NylonReferenceFit:NylonBodyFit):null;
  const string=NylonModel.stringFor(midi,{dropD}),{number,openMidi,fret,wound}=string;
  const fundamental=440*2**((midi-69)/12),count=Math.ceil(rate*3.6);
  // A fret shortens the vibrating length; drop D lowers the sixth string tension.
  const openFrequency=440*2**((openMidi-69)/12);
  const tension=[0,65,60,65,60,70,70,65][number]*(number===6&&dropD?2**(-4/12):1);
  const impedance=tension/(2*.65*openFrequency);
  const bridgeRate=18*Math.sqrt(impedance/.35)*Math.sqrt(Math.max(0,body)/.48);
  // Position control spans physical distances from bridge to finger on the open string.
  const pluckPosition=Math.min(.46,Math.max(.04,(fit?fit.pluckScale*(.04+.32*position):(.04+.32*position))*2**(Math.min(fret,36)/12)));
  const shape=contact?NylonContact.create(rate,nail):null;
  const modes=Math.min(wound?96:48,Math.floor(rate*.43/fundamental));
  const sr=new Float64Array(modes*2),si=new Float64Array(modes*2),sw=new Float64Array(modes*2);
  const sc=new Float64Array(modes*2),ss=new Float64Array(modes*2);
  const thirdAmount=fit&&referenceTone&&number===3?Math.max(0,Math.min(1,thirdTone)):0;
  const firstAmount=fit&&referenceTone&&number===1?Math.max(0,Math.min(1,firstTone)):0;
  const firstProfile=firstAmount?NylonFirstExcitation.at(fret):null;
  const baseStiffness=(thirdAmount?(.000003+(NylonThirdExcitation.stiffness-.000003)*thirdAmount):(wound?.000007:.000003))*Math.min(3,2**(fret/12));
  const stiffness=firstProfile?baseStiffness*(1-firstAmount)+firstProfile.stiffness*firstAmount:baseStiffness;
  const woundRelease=!!(fit&&referenceTone&&wound&&number>=4&&number<=7);
  const texture=woundRelease?Math.max(0,Math.min(1,stringTexture))*Math.max(0,Math.min(1,(50-openMidi)/10)):0;
  const highAmount=woundRelease?Math.max(0,Math.min(1,highDecay)):0;
  const highLoss=new Float64Array(modes*2),highStep=new Float64Array(modes*2);
  let originalPluckEnergy=0,tunedPluckEnergy=0;
  let stringNorm=0;
  for(let n=1;n<=modes;n++)for(let p=0;p<2;p++){
   const k=(n-1)*2+p;
   let frequency=fundamental*n*Math.sqrt((1+stiffness*n*n)/(1+stiffness))*(p?1+(wound?.00045:.0007):1);
   const excitationFrequency=frequency;
   if(texture)frequency=fundamental*n*Math.sqrt((1+stiffness*n*n)/(1+stiffness))*(1+(p?.00045:0)*(1-texture)+(p?1:-1)*.0025*texture);
   // Intrinsic string loss only; bridge loss is generated by the exchange below.
   const loss=(firstProfile?firstAmount*firstProfile.lossPerSecond[Math.min(n-1,firstProfile.lossPerSecond.length-1)]:0)+(thirdAmount?thirdAmount*NylonThirdExcitation.lossPerSecond[Math.min(n-1,NylonThirdExcitation.lossPerSecond.length-1)]:0)+(woundRelease?NylonWoundExcitation.loss(frequency,openMidi):0)+(.24+.003*Math.min(fret,24))*(p?.7:1)+(wound?.00009:.00013)*frequency
     +(wound?.000000018:.00000025)*frequency*frequency;
   // Preserve the release attack, then damp upper string modes smoothly.
   const highMix=Math.max(0,Math.min(1,(frequency-720)/160));
   highLoss[k]=30*highAmount*highMix*highMix*(3-2*highMix);
   highStep[k]=Math.exp(-highLoss[k]/rate);
   const r=Math.exp(-loss/rate),angle=2*Math.PI*frequency/rate;
   sc[k]=r*Math.cos(angle);ss[k]=r*Math.sin(angle);
   const response=shape?NylonContact.response(shape,excitationFrequency):{gain:Math.exp(-((excitationFrequency/(wound?6000:5200))**1.4)),phase:0};
   // Displacement plus a small release velocity over a finite finger contact.
   // The two initial conditions avoid perfectly repeated spectral zeroes.
   const displacement=Math.sin(Math.PI*n*pluckPosition);
   const velocity=(.18+.55*nail)*Math.sin(Math.PI*n*Math.min(.49,pluckPosition+.035));
   const originalAmplitude=Math.hypot(displacement,velocity)/n*response.gain*(p?.25:.75);
   const amplitude=originalAmplitude*(firstProfile?10**(firstAmount*firstProfile.gainDb[Math.min(n-1,firstProfile.gainDb.length-1)]/20):1)*(thirdAmount?10**(thirdAmount*NylonThirdExcitation.gainDb[Math.min(n-1,NylonThirdExcitation.gainDb.length-1)]/20):1)*(texture?(p?(.25+.15*texture)/.25:(.75-.15*texture)/.75):1)*(woundRelease?NylonWoundExcitation.gain(n,openMidi,excitationFrequency):1);
   let referenceAmplitude=originalAmplitude;
   if(thirdAmount||firstAmount){
    // Keep the baseline pluck energy when stiffness shifts the release spectrum.
    const baseStiffness=.000003*Math.min(3,2**(fret/12));
    const baseFrequency=fundamental*n*Math.sqrt((1+baseStiffness*n*n)/(1+baseStiffness))*(p?1+.0007:1);
    const baseGain=shape?NylonContact.response(shape,baseFrequency).gain:Math.exp(-((baseFrequency/5200)**1.4));
    referenceAmplitude=Math.hypot(displacement,velocity)/n*baseGain*(p?.25:.75);
   }
   originalPluckEnergy+=referenceAmplitude**2;tunedPluckEnergy+=amplitude**2;
   const phase=Math.atan2(velocity,displacement)+(p?.24:0)+response.phase;
   sr[k]=amplitude*Math.sin(phase);si[k]=-amplitude*Math.cos(phase);
   sw[k]=p?.23+.42*texture:1;stringNorm+=sw[k]**2;
  }
  // Redistribute a fixed pluck energy across the wound-string modes.
  if((woundRelease||thirdAmount||firstAmount)&&tunedPluckEnergy>0){const scale=Math.sqrt(originalPluckEnergy/tunedPluckEnergy);for(let k=0;k<sr.length;k++){sr[k]*=scale;si[k]*=scale}}
  stringNorm=Math.sqrt(stringNorm);for(let k=0;k<sw.length;k++)sw[k]/=stringNorm;
  const extraContactModes=thirdAmount&&body>0&&attack>0&&NylonThirdExcitation.contactEnergyFraction>0?[[5600,1400,0,.25],[7400,1800,0,.25],[9200,2400,0,.2]]:[];
  const definitions=[...NylonBridgeModel.bodyModes,...extraContactModes].filter(mode=>mode[0]<rate*.45);
  const br=new Float64Array(definitions.length),bi=new Float64Array(definitions.length),bw=new Float64Array(definitions.length);
  const bc=new Float64Array(definitions.length),bs=new Float64Array(definitions.length),radiation=new Float64Array(definitions.length),bodyLoss=new Float64Array(definitions.length);
  const fractions=new Float64Array(definitions.length),rc=new Float64Array(definitions.length),rs=new Float64Array(definitions.length);
  let bodyNorm=0;
  for(let k=0;k<definitions.length;k++){
   const [frequency,loss,participation,radiativeFraction]=definitions[k],r=Math.exp(-loss/rate),angle=2*Math.PI*frequency/rate;
   bc[k]=r*Math.cos(angle);bs[k]=r*Math.sin(angle);bw[k]=participation;bodyNorm+=participation**2;
   // The remainder of the loss is internal body dissipation, not audible output.
   bodyLoss[k]=1-r*r;
   const fitted=fit&&k<NylonBridgeModel.bodyModes.length;
   fractions[k]=fitted?fit.radiativeFractions[k]:radiativeFraction;
   rc[k]=fitted?Math.cos(fit.radiationPhases[k]):1;rs[k]=fitted?Math.sin(fit.radiationPhases[k]):0;
   radiation[k]=Math.sqrt(2*rate*bodyLoss[k]*fractions[k]);
  }
  bodyNorm=Math.sqrt(bodyNorm);for(let k=0;k<bw.length;k++)bw[k]/=bodyNorm;
  // Normalization affects the angle, not each physical pair's coupling strength.
  const theta=bridgeRate*stringNorm*bodyNorm/rate;
  const cm1=-2*Math.sin(theta/2)**2,sine=Math.sin(theta);
  const exchange=NylonCoupledModel.exchange;
  // A small part of the pluck energy travels in the first short bridge-force pulse.
  // Transfer it through the same body port, rather than mixing an audible click/noise.
  const er=new Float64Array(1),ei=new Float64Array(1),ew=new Float64Array([1]);
  const attackAmount=Math.max(0,Math.min(1,attack));
  const pulse=attackAmount>0&&body>0?NylonContact.create(rate,nail).force:null;
  let releaseEnergy=0,releaseRemainder=0;
  if(pulse){
   let stored=0;for(let k=0;k<sr.length;k++)stored+=sr[k]**2+si[k]**2;
   const fraction=.003*attackAmount*(.5+.5*nail);
   releaseEnergy=stored*fraction;const scale=Math.sqrt(1-fraction);
   for(let k=0;k<sr.length;k++){sr[k]*=scale;si[k]*=scale}
   er[0]=Math.sqrt(releaseEnergy);
  }
  // A finite contact reservoir excites short, aperiodic high body modes.
  // It uses a separate orthogonal port; no noise is mixed into the audio output.
  const cr=new Float64Array(1),ci=new Float64Array(1),cw=new Float64Array([1]);
  const contactWeights=new Float64Array(definitions.length);
  let contactForce=null,contactEnergy=0;
  if(extraContactModes.length){
   let stored=0;for(let k=0;k<sr.length;k++)stored+=sr[k]**2+si[k]**2;
   const fraction=thirdAmount*NylonThirdExcitation.contactEnergyFraction;
   contactEnergy=stored*fraction;cr[0]=Math.sqrt(contactEnergy);
   for(let k=0;k<sr.length;k++){sr[k]*=Math.sqrt(1-fraction);si[k]*=Math.sqrt(1-fraction)}
   let weightNorm=0;
   for(let k=0;k<definitions.length;k++){const f=definitions[k][0];contactWeights[k]=f>=2500?Math.min(1,(f-2000)/2000):0;weightNorm+=contactWeights[k]**2}
   for(let k=0;k<contactWeights.length;k++)contactWeights[k]/=Math.sqrt(weightNorm);
   const length=Math.round(rate*NylonThirdExcitation.contactDuration),hp=Math.exp(-2*Math.PI*2000/rate),lp=1-Math.exp(-2*Math.PI*10000/rate);
   contactForce=new Float64Array(length);let seed=(midi*2654435761)>>>0,previous=0,high=0,low=0;
   for(let i=0;i<length;i++){seed=(Math.imul(seed,1664525)+1013904223)>>>0;const white=seed/2147483648-1;high=white-previous+hp*high;previous=white;low+=lp*(high-low);const time=i/rate,envelope=(1-Math.exp(-time/.0008))*Math.exp(-time/NylonThirdExcitation.contactTimeConstant)*Math.min(1,(length-1-i)/(rate*.008));contactForce[i]=.05*low*envelope}
  }
  const energy=()=>{let stringEnergy=0,bodyEnergy=0;for(let k=0;k<sr.length;k++)stringEnergy+=sr[k]**2+si[k]**2;for(let k=0;k<br.length;k++)bodyEnergy+=br[k]**2+bi[k]**2;const excitation=er[0]**2+ei[0]**2+cr[0]**2+ci[0]**2;return {string:stringEnergy,body:bodyEnergy,excitation,total:stringEnergy+bodyEnergy+excitation}};
  const initialEnergy=energy().total,initialBodyEnergy=energy().body;
  let maximum=initialEnergy,maximumBody=0,previousInput=0,previousOutput=0,peak=0,radiatedEnergy=0;
  const out=new Float32Array(count),pole=Math.exp(-2*Math.PI*45/rate);
  if(diagnostics)diagnostics.snapshots=[];
  let cursor=0,finished=false;
  return {next:()=>{
   if(finished)return {done:true};
   const end=Math.min(count,cursor+1024);
   for(let i=cursor;i<end;i++){
   for(let k=0;k<sr.length;k++){const re=sr[k],im=si[k];sr[k]=sc[k]*re-ss[k]*im;si[k]=ss[k]*re+sc[k]*im}
   if(highAmount&&i>=rate*.025){
    const q=Math.min(1,(i/rate-.025)/.025),mix=q*q*(3-2*q);
    for(let k=0;k<sr.length;k++)if(highLoss[k]){const damp=mix===1?highStep[k]:Math.exp(-highLoss[k]*mix/rate);sr[k]*=damp;si[k]*=damp}
   }
   for(let k=0;k<br.length;k++){const re=br[k],im=bi[k];if(diagnostics)radiatedEnergy+=bodyLoss[k]*(re*re+im*im)*fractions[k];br[k]=bc[k]*re-bs[k]*im;bi[k]=bs[k]*re+bc[k]*im}
   if(theta)exchange(sr,si,sw,br,bi,bw,cm1,sine);
   if(pulse&&i<pulse.length){
    const angle=Math.PI*.5*pulse[i];
    exchange(er,ei,ew,br,bi,bw,-2*Math.sin(angle/2)**2,Math.sin(angle));
    // Energy still held by the detached contact no longer belongs to the instrument.
    if(i===pulse.length-1){releaseRemainder=er[0]**2+ei[0]**2;er[0]=ei[0]=0}
   }
   if(contactForce&&i<contactForce.length){
    const angle=contactForce[i];exchange(cr,ci,cw,br,bi,contactWeights,-2*Math.sin(angle/2)**2,Math.sin(angle));
    if(i===contactForce.length-1){releaseRemainder+=cr[0]**2+ci[0]**2;cr[0]=ci[0]=0}
   }
   // The radiating body states are the output, not a separately equalized string.
   let input=0;for(let k=0;k<br.length;k++)input+=radiation[k]*(fit?rc[k]*br[k]+rs[k]*bi[k]:br[k]);
   // At zero body, expose the unamplified string so the slider has a dry endpoint.
   if(body===0)for(let k=0;k<sr.length;k++)input+=sr[k];
   const time=i/rate;input*=1-Math.exp(-time/(.0006+.0012*(1-nail)));
   if(thirdAmount&&time<NylonThirdExcitation.onsetRiseSeconds){
    const onset=.5-.5*Math.cos(Math.PI*time/NylonThirdExcitation.onsetRiseSeconds);
    input*=1-thirdAmount+thirdAmount*onset;
   }
   if(firstAmount&&time<NylonFirstExcitation.onsetRiseSeconds){
    const onset=.5-.5*Math.cos(Math.PI*time/NylonFirstExcitation.onsetRiseSeconds);
    input*=1-firstAmount+firstAmount*onset;
   }
   const high=input-previousInput+pole*previousOutput;previousInput=input;previousOutput=high;
   out[i]=high*Math.min(1,(count-1-i)/(rate*.06));peak=Math.max(peak,Math.abs(out[i]));
   if(diagnostics&&i%256===0){const state=energy();maximum=Math.max(maximum,state.total);maximumBody=Math.max(maximumBody,state.body);if(i%4096===0)diagnostics.snapshots.push({time,...state,bodyModeEnergies:Array.from(br,(v,k)=>v*v+bi[k]**2),partials:Array.from({length:modes},(_,n)=>sr[2*n]**2+si[2*n]**2+sr[2*n+1]**2+si[2*n+1]**2)})}
  }
  cursor=end;if(cursor<count)return {done:false};
  finished=true;
  if(diagnostics)Object.assign(diagnostics,{initialEnergy,maxEnergy:maximum,maxBodyEnergy:maximumBody,finalEnergy:energy().total,radiatedEnergy,rawPeak:peak,initialBodyEnergy,impedance,pluckPosition,releaseEnergy,releaseRemainder,contactEnergy});
  if(peak>0)for(let i=0;i<count;i++)out[i]*=.8/peak;
  return {done:true,value:out};
  }};
 }
};
