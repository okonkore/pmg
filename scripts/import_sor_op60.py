"""Regenerate Sor Op.60 samples from vendored Mutopia MIDI (standard library)."""
import hashlib
import json
from pathlib import Path
from import_bwv1012 import read_notes

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / 'scripts/score-sources/sor-op60'

def build():
    songs, manifest = {}, []
    for number, bpm, meter, shift, license_version in [
        (1, 112, [4, 4], -12, '2.5'), (2, 108, [3, 4], -12, '2.5'),
        (3, 112, [4, 4], 0, '3.0'), (4, 108, [3, 4], 0, '2.5'),
        (5, 80, [6, 8], 0, '3.0'), (12, 80, [2, 4], 0, '3.0'),
    ]:
        name = f'sor_op60-{number:02d}'
        base = f'https://www.mutopiaproject.org/ftp/SorF/O60/{name}/{name}'
        data = (SOURCES / (name + '.mid')).read_bytes()
        events = [[at, pitch + shift, duration] for at, pitch, duration in read_notes(data)]
        assert all(40 <= pitch <= 88 for _, pitch, _ in events)
        title = f'Fernando Sor · Op.60 No.{number}'
        engraver = 'Hajo Dezelski' if number == 12 else 'Fabrice De Volder'
        source = {'credit': f'Fernando Sor / {engraver} / Mutopia',
                  'license': 'CC BY-SA ' + license_version, 'url': base + '.ly'}
        songs[f'sor60_{number}'] = {
            'score': {'title': title, 'bpm': bpm, 'meter': meter, 'events': events},
            'label': title, 'option': f'Op.60 第{number}番',
            'edition': '全曲・反復なし', 'source': source,
        }
        manifest.append(dict(number=number, midi=base+'.mid', source=source,
                             sha256=hashlib.sha256(data).hexdigest(), pitchShift=shift,
                             notes=len(events), beats=max(at+d for at, _, d in events), bpm=bpm))
    (ROOT / 'synth-demo/sor-op60.js').write_text(
        '// Fernando Sor, Op.60 Nos.1–5,12. Engraving: Fabrice De Volder (1–5), Hajo Dezelski (12) / Mutopia.\n'
        '// Adapted under CC BY-SA 2.5 (1,2,4) / 3.0 (3,5,12). See scripts/score-sources/sor-op60.\n'
        '// Generated by scripts/import_sor_op60.py; guitar sounding pitch; repeats omitted.\n'
        'const sorSongs = ' + json.dumps(songs, ensure_ascii=False, separators=(',', ':')) + ';\n')
    (SOURCES / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n')

if __name__ == '__main__':
    build()
