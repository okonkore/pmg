"""Convert vendored LilyPond/MIDI to PMG events. Optional: --lilypond /path/to/lilypond.

Default regeneration uses vendored MIDI and the standard library only.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile
from import_bwv1012 import read_notes

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / 'scripts/score-sources/repertoire-batch1'
RAW = 'https://raw.githubusercontent.com/MutopiaProject/MutopiaProject/master/ftp/'
PIECES = [
    ('menuet1007', 'bwv1007_menuet_i', 'J. S. Bach · BWV 1007 — Menuet I', 'Menuet I（メヌエット I）', 120, 517),
    ('menuet2_1007', 'bwv1007_menuet_ii', 'J. S. Bach · BWV 1007 — Menuet II', 'Menuet II（メヌエット II）', 120, 517),
    ('sor35_22', 'sorf_op35_no22', 'Fernando Sor · Op.35 No.22', 'Op.35 第22番', 100, 1850),
]

def compile_midi(executable):
    with tempfile.TemporaryDirectory() as folder:
        for key, name, *_ in PIECES:
            output = str(SOURCES / name)
            if key == 'sor35_22':
                source = SOURCES / (name + '.ly')
            else:
                variable = 'menuetI' if key == 'menuet1007' else 'menuetII'
                source = Path(folder) / (name + '.ly')
                source.write_text('\\version "2.24.4"\n\\include "' + str(SOURCES / (name + '.ly')) + '"\n'
                                  '\\score { { \\clef "bass" \\transpose c c, { \\' + variable +
                                  ' } } \\midi { \\tempo 4 = 120 } }\n')
            subprocess.run([executable, '-dno-print-pages', '-dbackend=null', '-o', output, str(source)], check=True)

def build():
    songs, manifest = {}, []
    for key, name, title, option, bpm, source_id in PIECES:
        sor = source_id == 1850
        data = (SOURCES / (name + '.midi')).read_bytes()
        events = read_notes(data)  # MIDI already at sounding pitch; no additional transposition.
        source = {
            'credit': 'Fernando Sor / Glen Larsen / Mutopia (2013)' if sor else 'J. S. Bach / Andreas Scherer / Mutopia (2018)',
            'license': 'CC BY-SA 3.0' if sor else 'Public Domain',
            'licenseUrl': 'https://creativecommons.org/licenses/by-sa/3.0/' if sor else 'https://creativecommons.org/licenses/publicdomain/',
            'url': f'https://www.mutopiaproject.org/cgibin/piece-info.cgi?id={source_id}',
            'modifications': 'LilyPond 2.24.4 MIDI converted to quarter-note events; repeats omitted; all voices retained; fixed audition tempo; playback articulation is applied separately.',
            'pitch': 'Original guitar sounding pitch; MIDI shift 0.' if sor else 'Original cello sounding pitch; source wrapper transpose c c, applied once; MIDI shift 0. Includes notes below standard guitar E2; not a guitar arrangement.',
            'terms': 'Adapted score data: CC BY-SA 3.0; retain attribution and license; share adaptations under the same license. Application code is separate.' if sor else 'Score edition placed in the public domain by the typesetter.',
        }
        songs[key] = {'score': {'title': title, 'bpm': bpm, 'meter': [3,4], 'endBeat': 144 if sor else 72, 'events': events},
                      'label': title, 'option': option,
                      'edition': '全曲・反復なし・ギター実音' if sor else '全曲・反復なし・チェロ原音域（標準ギターE2未満あり）', 'source': source}
        end = max(at + d for at, _, d in events)
        manifest.append({'key': key, 'file': name, 'source': source,
                         'lilypondUrl': RAW + ('SorF/O35/sorf_op35_no22/' if sor else 'BachJS/BWV1007/bwv1007/bwv1007-lys/') + name + '.ly',
                         'sha256': {ext: hashlib.sha256((SOURCES / (name + ext)).read_bytes()).hexdigest() for ext in ['.ly', '.midi']},
                         'notes': len(events), 'noteEndBeats': end, 'scoreBars': 48 if sor else 24,
                         'scoreBeats': 144 if sor else 72, 'pitchRange': [min(e[1] for e in events),max(e[1] for e in events)],
                         'belowE2': sum(e[1] < 40 for e in events), 'midiPitchShift': 0, 'bpm': bpm})
    (ROOT / 'synth-demo/repertoire-batch1.js').write_text(
        '// Generated by scripts/import_repertoire_batch1.py; provenance and licenses in each source object.\n'
        '// Sor adapted score data CC BY-SA 3.0; Bach edition Public Domain. Application code licensed separately.\n'
        'const repertoireBatch1 = ' + json.dumps(songs, ensure_ascii=False, separators=(',', ':')) + ';\n')
    (SOURCES / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps([{k:v for k,v in m.items() if k not in ('source','sha256','lilypondUrl')} for m in manifest], indent=2))

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--lilypond')
    args = parser.parse_args()
    if args.lilypond:
        compile_midi(args.lilypond)
    build()
