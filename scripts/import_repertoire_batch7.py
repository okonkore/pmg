"""Full performed forms from licensed solo-guitar editions; original MIDI voices retained."""
import argparse,hashlib,json,re,subprocess,tempfile
from pathlib import Path
from import_bwv1012 import read_notes
from import_repertoire_batch4 import VOICE_MIDI
ROOT=Path(__file__).resolve().parents[1];SOURCES=ROOT/'scripts/score-sources/repertoire-batch7'
PIECES=[
 dict(key='menuet1006a',file='bwv-1006a_4g',name='Menuet I',japanese='メヌエット I',bpm=96,meter=[3,4],writtenBars=34,beats=204,sourceId=1501,form=[[0,24],[0,24],[24,102],[24,102]]),
 dict(key='menuet2_1006a',file='bwv-1006a_5g',name='Menuet II',japanese='メヌエット II',bpm=96,meter=[3,4],writtenBars=32,beats=192,sourceId=1502,form=[[0,48],[0,48],[48,96],[48,96]]),
 dict(key='bourree1006a',file='bwv-1006a_6g',name='Bourrée',japanese='ブーレ',bpm=120,meter=[4,4],writtenBars=36,beats=292,sourceId=1498,form=[[0,65],[0,65],[65,146],[65,146]])
]

def expand(raw,form):
 result=[];offset=0
 for start,end in form:
  section=[e for e in raw if start<=e[0]<end]
  if not section or any(a+d>end+1e-8 for a,p,d in section):raise ValueError('Section boundary cuts a source note')
  result.extend([[offset+(a-start),p,d] for a,p,d in section]);offset+=end-start
 return result,offset

def compile_midi(executable):
 with tempfile.TemporaryDirectory() as directory:
  for p in PIECES:
   original=SOURCES/(p['file']+'.ly');text=subprocess.run([str(Path(executable).with_name('convert-ly')),str(original)],capture_output=True,text=True,check=True).stdout
   text,n=re.subn(r'\\midi\s*\{',lambda _: '\\midi { '+VOICE_MIDI,text);assert n==1
   tmp=Path(directory)/(p['file']+'.ly');tmp.write_text(text)
   subprocess.run([executable,'-dno-print-pages','-dbackend=null','-o',str(SOURCES/p['file']),str(tmp)],check=True)

def build():
 songs,manifest={},[]
 for p in PIECES:
  raw=read_notes((SOURCES/(p['file']+'.midi')).read_bytes());events,end=expand(raw,p['form']);assert end==p['beats']
  events=[[a,pitch-12,d] for a,pitch,d in events]
  source=dict(credit='J. S. Bach / guitar edition Hajo Dezelski / Mutopia (2008), after BGA 1879 vol.42',license='CC BY-SA 3.0',licenseUrl='https://creativecommons.org/licenses/by-sa/3.0/',url=f"https://www.mutopiaproject.org/cgibin/piece-info.cgi?id={p['sourceId']}",modifications='Full individual movement; A A B B repeats. Official convert-ly / LilyPond 2.24.4; separate MIDI voices, overlaps retained. Guitar written pitches lowered 12 semitones. Fixed audition tempo chosen; source has no tempo. Trill signs are not realized. No automatic Menuet I return. App articulation separate.',pitch='Guitar sounding E2-B4, standard E2 A2 D3 G3 B3 E4 range. Edition marked Guitar (staff named Laute); not a verified fingering/string-choice simulation.',terms='Derived score data CC BY-SA 3.0; retain attribution, license and changes; share adaptations under the same license. Application code separate.',endingStatus='反復と終端確認済み。')
  if p['key']=='bourree1006a':
   source['modifications']+=' Edition retains a quarter-note pickup plus 16/20 full bars, including each final silent quarter; these gaps are preserved, not silently corrected.'
   source['endingStatus']='版の各節末の1拍休止を保持（弱起を含む65拍＋81拍を各2回）。'
  assert all(len(v)<=500 for v in source.values())
  title='J. S. Bach · BWV 1006a — '+p['name']
  songs[p['key']]=dict(score=dict(title=title,bpm=p['bpm'],meter=p['meter'],endBeat=end,events=events),label=title,option=p['name']+'（'+p['japanese']+'）',edition='全曲・反復あり・ギター実音'+('・版の節末休止を保持' if p['key']=='bourree1006a' else ''),source=source)

  manifest.append({**p,'source':source,'rawNotes':len(raw),'notes':len(events),'noteEndBeats':max(a+d for a,p,d in events),'pitchRange':[min(e[1] for e in events),max(e[1] for e in events)],'tempoBasis':'fixed audition choice, no source tempo','pitchShift':-12,'lilypondUrl':'https://raw.githubusercontent.com/MutopiaProject/MutopiaProject/master/ftp/'+'BachJS/BWV1006a/'+p['file']+'/'+p['file']+'.ly','sha256':{p['file']+ext:hashlib.sha256((SOURCES/(p['file']+ext)).read_bytes()).hexdigest() for ext in ['.ly','.midi']}})
 (ROOT/'synth-demo/repertoire-batch7.js').write_text('// Generated by import_repertoire_batch7.py. Score data CC BY-SA 3.0, Hajo Dezelski guitar edition; application code separate.\nconst repertoireBatch7 = '+json.dumps(songs,ensure_ascii=False,separators=(',',':')).replace('],[','],\n[')+';\n')
 (SOURCES/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n');print([(m['key'],m['notes'],m['beats'],m['pitchRange']) for m in manifest])
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--lilypond');args=parser.parse_args()
 if args.lilypond:compile_midi(args.lilypond)
 build()
