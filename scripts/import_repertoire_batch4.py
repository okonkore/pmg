"""Sor Op.1 Nos.1,2,6: licensed edition, full sections, sounding guitar pitch.

Original source bytes remain untouched. Use --lilypond PATH to recompile with
2.24.4 plus sibling convert-ly; otherwise use vendored per-voice MIDI.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile
from import_bwv1012 import read_notes

ROOT=Path(__file__).resolve().parents[1]
SOURCES=ROOT/'scripts/score-sources/repertoire-batch4'
PIECES=[
    dict(key='sor1_1',file='sor_op1_1',number=1,name='Andante',japanese='アンダンテ',meter=[3,4],bpm=84,beats=54,bars=18,pickup=0,final=3,shift=0,license='4.0',year=2015,sourceId=413),
    dict(key='sor1_2',file='sor_op1_2',number=2,name='Waltz',japanese='ワルツ',meter=[3,8],bpm=90,beats=72,bars=48,pickup=.5,final=1,shift=-12,license='4.0',year=2015,sourceId=452),
    dict(key='sor1_6',file='sor_op_1_6',number=6,name='Marcia',japanese='マルチャ（6弦F2）',meter=[4,4],bpm=96,beats=160,bars=40,pickup=0,final=4,shift=-12,license='3.0',year=2013,sourceId=458),
]
VOICE_MIDI="\\context { \\Score midiChannelMapping = #'voice } \\context { \\Staff \\remove \"Staff_performer\" } \\context { \\Voice \\consists \"Staff_performer\" }"


def compile_midi(executable):
    converter=str(Path(executable).resolve().with_name('convert-ly'))
    with tempfile.TemporaryDirectory() as directory:
        for p in PIECES:
            original=SOURCES/(p['file']+'.ly')
            text=subprocess.run([converter,str(original)],check=True,capture_output=True,text=True).stdout
            text,count=re.subn(r'\\midi\s*\{',lambda _: '\\midi { '+VOICE_MIDI,text)
            assert count==1
            temporary=Path(directory)/(p['file']+'.ly');temporary.write_text(text)
            subprocess.run([executable,'-dno-print-pages','-dbackend=null','-o',str(SOURCES/p['file']),str(temporary)],check=True)


def build():
    songs,manifest={},[]
    for p in PIECES:
        midi=SOURCES/(p['file']+'.midi');original=SOURCES/(p['file']+'.ly')
        events=[[at,pitch+p['shift'],duration] for at,pitch,duration in read_notes(midi.read_bytes())]
        title=f"Fernando Sor · Op.1 No.{p['number']} — {p['name']}"
        tuning=[64,59,55,50,45,41] if p['number']==6 else [64,59,55,50,45,40]
        pitch=('Source explicitly requires sixth string F2: low to high F2 A2 D3 G3 B3 E4. ' if p['number']==6 else 'Standard guitar tuning E2 A2 D3 G3 B3 E4. ')
        pitch+=('Source already encodes sounding pitch; MIDI shift 0.' if p['shift']==0 else 'Source MIDI is written treble register; shifted -12 semitones to guitar sounding pitch.')
        source={
            'credit':f"Fernando Sor / Mark Van den Borre / Mutopia ({p['year']})",
            'license':'CC BY-SA '+p['license'],
            'licenseUrl':f"https://creativecommons.org/licenses/by-sa/{p['license']}/",
            'url':f"https://www.mutopiaproject.org/cgibin/piece-info.cgi?id={p['sourceId']}",
            'modifications':f"Complete individual piece, each volta section once. Official convert-ly syntax update; LilyPond 2.24.4, separate MIDI tracks per voice; grace/tuplet timing retained. MIDI pitch shift {p['shift']}; end marker {p['beats']} quarter beats includes final rests. Follows this credited edition, including its editorial readings; no claim of urtext. App articulation separate.",
            'pitch':pitch,
            'terms':f"Adapted score data: CC BY-SA {p['license']}; retain attribution, license and modification notice; share adaptations under the same license. Application code is separate.",
        }
        assert all(len(value)<=500 for value in source.values())
        if p['number']==6:
            source['pitch']+=' Required tuning is not automatically applied; note-pitch playback is not a verified string-choice or fingering simulation.'
            source['requiredTuning']={'instrument':'guitar','pitchesLowToHigh':[41,45,50,55,59,64],'automaticallyApplied':False}
        songs[p['key']]={'score':dict(title=title,bpm=p['bpm'],meter=p['meter'],endBeat=p['beats'],events=events),'label':title,'option':f"Op.1 第{p['number']}番 · {p['japanese']}",'edition':'全曲・反復なし・ギター実音'+('・6弦F2' if p['number']==6 else ''),'source':source}
        raw=f"https://raw.githubusercontent.com/MutopiaProject/MutopiaProject/master/ftp/SorF/O1/{p['file']}/{p['file']}.ly"
        manifest.append({**p,'source':source,'lilypondUrl':raw,'sha256':{f.name:hashlib.sha256(f.read_bytes()).hexdigest() for f in [original,midi]},'notes':len(events),'noteEndBeats':max(a+d for a,_,d in events),'pitchRange':[min(e[1] for e in events),max(e[1] for e in events)],'tuningHighToLow':tuning,'humanPerformanceVerified':False,'tempoBasis':'fixed audition choice; source MIDI has no explicit tempo' if p['number']==6 else ('source dotted-quarter=60 equals quarter=90' if p['number']==2 else 'source quarter=84')})
    (ROOT/'synth-demo/repertoire-batch4.js').write_text('// Generated by scripts/import_repertoire_batch4.py. Sor/Mark Van den Borre score data: CC BY-SA 4.0 (Nos.1,2), 3.0 (No.6).\n// Per-song credits, licenses, tuning and changes retained. Application code separate.\nconst repertoireBatch4 = '+json.dumps(songs,ensure_ascii=False,separators=(',',':')).replace('],[','],\n[')+';\n')
    (SOURCES/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps([{k:m[k] for k in ['key','notes','beats','noteEndBeats','pitchRange','shift']} for m in manifest],indent=2))


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--lilypond');args=parser.parse_args()
    if args.lilypond:compile_midi(args.lilypond)
    build()
