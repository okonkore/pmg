"""Regenerate Sor Op.6 No.8 from vendored Mutopia MIDI, using the standard library."""
import hashlib
import json
from pathlib import Path
from import_bwv1012 import read_notes

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / 'scripts/score-sources/sor-op6'


def build():
    data = (SOURCES / 'sorf-op6n08.mid').read_bytes()
    events = read_notes(data)
    assert all(40 <= pitch <= 88 for _, pitch, _ in events)
    source = {
        'credit': 'Fernando Sor / Glen Larsen / Mutopia',
        'license': 'CC BY-SA 4.0',
        'url': 'https://www.mutopiaproject.org/cgibin/piece-info.cgi?id=2128',
    }
    songs = {'sor6_8': {
        'score': {'title': 'Fernando Sor · Op.6 No.8 — Andantino',
                  'bpm': 88, 'meter': [3, 4], 'events': events},
        'label': 'Fernando Sor · Op.6 No.8 — Andantino',
        'option': 'Op.6 第8番（Andantino）', 'edition': '全曲', 'source': source,
    }}
    (ROOT / 'synth-demo/sor-op6.js').write_text(
        '// Fernando Sor, Op.6 No.8. Engraving: Glen Larsen / Mutopia, 2016.\n'
        '// Adapted note events: CC BY-SA 4.0, https://creativecommons.org/licenses/by-sa/4.0/\n'
        '// Generated by scripts/import_sor_op6.py. Source MIDI pitch and note lengths retained.\n'
        'const sorOp6Songs = ' + json.dumps(songs, ensure_ascii=False, separators=(',', ':')) + ';\n')
    manifest = {
        'key': 'sor6_8', 'source': source,
        'midi': 'https://www.mutopiaproject.org/ftp/SorF/O6/sorf-op6n08/sorf-op6n08.mid',
        'sha256': hashlib.sha256(data).hexdigest(), 'notes': len(events),
        'beats': max(at + d for at, _, d in events), 'bpm': 88,
        'meter': [3, 4], 'pitchShift': 0,
    }
    (SOURCES / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')


if __name__ == '__main__':
    build()
